// Writes src/ui/chartprims.css (what build-css scoops up with the other sheets): the xy kinds' classes, the chart part's own
// rules and the eight kinds' classes, in that order. `bun src/engine/charts/gen.ts`; test/engine/chwire/page.test.ts fails when the file drifts.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const HERE = import.meta.dir, OUT = join(HERE, "../../ui/chartprims.css");
const PARTS = ["xy/xy.css", "page.css", "kinds/axis-kinds.css", "kinds/tree-kinds.css"];
export function chartPrimsCss(): string {
  const out = ["/* GENERATED by src/engine/charts/gen.ts from " + PARTS.join(", ") + ": edit those, then run `bun src/engine/charts/gen.ts`. */"];
  for (const p of PARTS) if (existsSync(join(HERE, p))) out.push(`/* ---- ${p} ---- */`, readFileSync(join(HERE, p), "utf8").trimEnd());
  return out.join("\n") + "\n";
}
if (import.meta.main) writeFileSync(OUT, chartPrimsCss());
